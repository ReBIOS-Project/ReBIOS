#ifndef VIRT__MSR_TABLE_H
#define VIRT__MSR_TABLE_H

#include <stddef.h>
#include <stdint.h>

struct msr_range {
    uint32_t first;
    uint32_t last;
};

struct msr_ranges {
    const struct msr_range *ranges;
    size_t count;
};

// The tables of a model's model-specific MSRs.
struct msr_model {
    uint32_t family;
    uint32_t model;
    const struct msr_ranges *const *tables;
    size_t count;
};

// The model-specific MSRs of an AMD family.
struct msr_family {
    uint32_t family;
    const struct msr_range *ranges;
    size_t count;
};

// Generated by tools/msr-table.py.
extern const struct msr_range msr_intel_architectural[];
extern const size_t msr_intel_architectural_count;
extern const struct msr_model msr_intel_models[];
extern const size_t msr_intel_model_count;
extern const struct msr_range msr_amd_architectural[];
extern const size_t msr_amd_architectural_count;
extern const struct msr_family msr_amd_families[];
extern const size_t msr_amd_family_count;

#endif
