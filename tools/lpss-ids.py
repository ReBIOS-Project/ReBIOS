# lpss-ids.py <Linux tree> <output.c>: generates the list of the device IDs of
# Intel's LPSS functions, those that Linux's drivers/mfd/intel-lpss-pci.c
# drives.
import os
import re
import sys

# c_layout.py sits beside the generators, which leave no bytecode in the tree.
sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from c_layout import NOTICE, count_decl, finish

DEVICE = re.compile(r'PCI_VDEVICE\(INTEL,\s*0x([0-9a-fA-F]{4})\)')
# As many as fit on a line of 99 columns.
PER_LINE = 12


def main():
    linux, out = sys.argv[1], sys.argv[2]
    with open(os.path.join(linux, 'drivers/mfd/intel-lpss-pci.c')) as f:
        ids = sorted({int(m.group(1), 16) for m in DEVICE.finditer(f.read())})
    if not ids:
        sys.exit('lpss-ids.py: no device IDs found')

    rows = []
    for i in range(0, len(ids), PER_LINE):
        rows.append('    ' + ' '.join('0x%04x,' % d for d in ids[i:i + PER_LINE]))
    text = '\n'.join(NOTICE) + '\n'
    text += ('\n// Generated by tools/lpss-ids.py from Linux 7.3\'s\n'
             '// drivers/mfd/intel-lpss-pci.c.\n\n')
    text += ('#include <stddef.h>\n#include <stdint.h>\n#include <virt/lpss_ids.h>\n'
             '#include <lib/util.h>\n\n')
    text += 'const uint16_t lpss_ids[] = {\n' + '\n'.join(rows) + '\n};\n\n'
    text += '\n'.join(count_decl('lpss_ids_count', 'lpss_ids'))
    with open(out, 'w') as f:
        f.write(finish(text + '\n'))


main()
