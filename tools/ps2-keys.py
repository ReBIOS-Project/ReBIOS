ROW = re.compile(r"^\s*(.*?)\s+07\s+([0-9A-Fa-f]{2})\s{2,}(.*)$")
USAGES = 0xe8


def code(text):
    """(extended, code) of a make column, or None."""
    parts = text.split()
    if len(parts) == 1 and re.fullmatch(r"[0-9A-Fa-f]{2}", parts[0]):
        return False, int(parts[0], 16)
    if len(parts) == 2 and parts[0].upper() == "E0":
        return True, int(parts[1], 16)
    return None


def main():
    rows = {}
    for line in open(sys.argv[1], errors="replace"):
        match = ROW.match(line)
        if match is None:
            continue
        name = re.sub(r"\s*\(Note.*?\)", "", match.group(1)).strip()
        usage = int(match.group(2), 16)
        columns = re.split(r"\s{2,}", match.group(3).strip())
        if len(columns) < 4:
            continue
        set1 = code(columns[0])
        set2 = code(columns[2])
        # The error reports and the keys it gives more than one code.
        if set1 is None or set2 is None or usage < 4 or usage >= USAGES:
            continue
        if set1[0] != set2[0]:
            raise SystemExit(f"{name}: extended in only one set")
        rows[usage] = (name, set1[0], set1[1], set2[1])
    # Spot checks against the table's own text.
    assert rows[0x04][2:] == (0x1e, 0x1c), rows[0x04]
    assert rows[0x29][2:] == (0x01, 0x76), rows[0x29]
    assert rows[0x52][1:] == (True, 0x48, 0x75), rows[0x52]
    assert rows[0xe0][2:] == (0x1d, 0x14), rows[0xe0]
    assert rows[0xe6][1:] == (True, 0x38, 0x11), rows[0xe6]
    assert 0x46 not in rows or rows[0x46][2] == 0x37

    out = [NOTICE, "// Generated by tools/ps2-keys.py from Microsoft's USB HID to "
           "PS/2 Scan Code", "// Translation Table of 2004-04-02.", "",
           "#include <virt/kbc_keys.h>", "",
           "const struct kbc_key kbc_keys[KBC_KEYS] = {"]
    for usage in sorted(rows):
        name, extended, set1, set2 = rows[usage]
        flag = "true" if extended else "false"
        row = f"    [{usage:#04x}] = {{ {set1:#04x}, {set2:#04x}, {flag} }},"
        # The table names some keys in other scripts.
        if name != "" and name.isascii():
            row += f" // {name}"
        out.append(row)
    out.append("};")
    open(sys.argv[2], "w").write("\n".join(out) + "\n")
    print(f"{len(rows)} keys")


main()
